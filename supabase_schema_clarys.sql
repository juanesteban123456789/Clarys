create or replace function public.adjust_stock(
    p_product_id bigint,
    p_movement_type text,
    p_quantity integer,
    p_reason text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_workshop_id uuid := public.current_workshop_id();
    v_previous integer;
    v_new integer;
begin
    if v_workshop_id is null then
        raise exception 'Usuario sin taller';
    end if;

    select stock into v_previous
    from public.products
    where id = p_product_id and workshop_id = v_workshop_id
    for update;

    if v_previous is null then
        raise exception 'Producto no encontrado';
    end if;

    if p_quantity <= 0 then
        raise exception 'Cantidad invalida';
    end if;

    if p_movement_type = 'Entrada' then
        v_new := v_previous + p_quantity;
    elsif p_movement_type = 'Salida' then
        v_new := greatest(0, v_previous - p_quantity);
    elsif p_movement_type = 'Ajuste' then
        v_new := p_quantity;
    else
        raise exception 'Tipo de movimiento invalido';
    end if;

    update public.products
    set stock = v_new, updated_at = now()
    where id = p_product_id and workshop_id = v_workshop_id;

    insert into public.inventory_movements (
        workshop_id, product_id, movement_type, quantity, previous_stock, new_stock, reason
    ) values (
        v_workshop_id, p_product_id, p_movement_type, p_quantity, v_previous, v_new, p_reason
    );
end;
$$;

create or replace function public.confirm_sale(
    p_customer_name text,
    p_customer_phone text,
    p_payment_method text,
    p_discount integer,
    p_status text,
    p_items jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
    v_workshop_id uuid := public.current_workshop_id();
    v_customer_id bigint;
    v_sale_id bigint;
    v_item jsonb;
    v_product_id bigint;
    v_quantity integer;
    v_unit_price integer;
    v_previous integer;
    v_total integer := 0;
begin
    if v_workshop_id is null then
        raise exception 'Usuario sin taller';
    end if;

    if jsonb_array_length(p_items) = 0 then
        raise exception 'La venta no tiene productos';
    end if;

    insert into public.customers (workshop_id, name, phone, total_orders, total_spent)
    values (v_workshop_id, coalesce(nullif(p_customer_name, ''), 'Cliente mostrador'), p_customer_phone, 0, 0)
    returning id into v_customer_id;

    insert into public.sales (workshop_id, customer_id, payment_method, status, discount, total)
    values (v_workshop_id, v_customer_id, p_payment_method, p_status, greatest(0, p_discount), 0)
    returning id into v_sale_id;

    for v_item in select * from jsonb_array_elements(p_items)
    loop
        v_product_id := (v_item->>'product_id')::bigint;
        v_quantity := (v_item->>'quantity')::integer;

        if v_quantity <= 0 then
            raise exception 'Cantidad invalida';
        end if;

        select stock, sale_price into v_previous, v_unit_price
        from public.products
        where id = v_product_id and workshop_id = v_workshop_id and active = true
        for update;

        if v_previous is null then
            raise exception 'Producto no encontrado';
        end if;

        if v_previous < v_quantity then
            raise exception 'Stock insuficiente';
        end if;

        insert into public.sale_items (sale_id, product_id, quantity, unit_price, subtotal)
        values (v_sale_id, v_product_id, v_quantity, v_unit_price, v_unit_price * v_quantity);

        update public.products
        set stock = stock - v_quantity,
            sold_units = sold_units + v_quantity,
            updated_at = now()
        where id = v_product_id and workshop_id = v_workshop_id;

        insert into public.inventory_movements (
            workshop_id, product_id, movement_type, quantity, previous_stock, new_stock, reason
        ) values (
            v_workshop_id, v_product_id, 'Salida', v_quantity, v_previous, v_previous - v_quantity,
            'Venta #' || v_sale_id
        );

        v_total := v_total + (v_unit_price * v_quantity);
    end loop;

    v_total := greatest(0, v_total - greatest(0, p_discount));

    update public.sales
    set total = v_total
    where id = v_sale_id;

    update public.customers
    set total_orders = total_orders + 1,
        total_spent = total_spent + v_total
    where id = v_customer_id;

    return v_sale_id;
end;
$$;

