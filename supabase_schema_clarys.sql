create extension if not exists pgcrypto;

create table if not exists public.workshops (
    id uuid primary key default gen_random_uuid(),
    owner_user_id uuid not null unique references auth.users(id) on delete cascade,
    name text not null,
    whatsapp text,
    currency text not null default 'COP',
    default_min_stock integer not null default 5,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
    user_id uuid primary key references auth.users(id) on delete cascade,
    workshop_id uuid not null references public.workshops(id) on delete cascade,
    role text not null check (role in ('admin', 'seller', 'customer')),
    created_at timestamptz not null default now()
);

create table if not exists public.products (
    id bigint generated by default as identity primary key,
    workshop_id uuid not null references public.workshops(id) on delete cascade,
    name text not null,
    description text,
    category text,
    purchase_price integer not null default 0,
    sale_price integer not null default 0,
    stock integer not null default 0 check (stock >= 0),
    min_stock integer not null default 0 check (min_stock >= 0),
    sizes text,
    colors text,
    sku text,
    image_url text,
    active boolean not null default true,
    sold_units integer not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.customers (
    id bigint generated by default as identity primary key,
    workshop_id uuid not null references public.workshops(id) on delete cascade,
    name text not null,
    phone text,
    total_orders integer not null default 0,
    total_spent integer not null default 0,
    created_at timestamptz not null default now()
);

create table if not exists public.sales (
    id bigint generated by default as identity primary key,
    workshop_id uuid not null references public.workshops(id) on delete cascade,
    customer_id bigint references public.customers(id) on delete set null,
    payment_method text not null default 'Pendiente',
    status text not null default 'Confirmada',
    discount integer not null default 0,
    total integer not null default 0,
    created_at timestamptz not null default now()
);

create table if not exists public.sale_items (
    id bigint generated by default as identity primary key,
    sale_id bigint not null references public.sales(id) on delete cascade,
    product_id bigint not null references public.products(id) on delete restrict,
    quantity integer not null check (quantity > 0),
    unit_price integer not null default 0,
    subtotal integer not null default 0
);

create table if not exists public.inventory_movements (
    id bigint generated by default as identity primary key,
    workshop_id uuid not null references public.workshops(id) on delete cascade,
    product_id bigint not null references public.products(id) on delete cascade,
    movement_type text not null check (movement_type in ('Entrada', 'Salida', 'Ajuste')),
    quantity integer not null check (quantity > 0),
    previous_stock integer not null default 0,
    new_stock integer not null default 0,
    reason text,
    created_at timestamptz not null default now()
);

create table if not exists public.contact_requests (
    id bigint generated by default as identity primary key,
    customer_name text not null,
    customer_phone text,
    items jsonb not null default '[]'::jsonb,
    ai_description text,
    status text not null default 'new',
    created_at timestamptz not null default now()
);

create or replace function public.current_workshop_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
    select p.workshop_id
    from public.profiles p
    where p.user_id = auth.uid()
    limit 1;
$$;

